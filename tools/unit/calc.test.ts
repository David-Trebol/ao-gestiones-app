import { calculateItemTotals, calculateShippingTotals, generateReferenceNumber, formatCurrency } from '../../expo/utils/calculations';
let fails = 0;
const eq = (name: string, got: any, exp: any) => { const ok = JSON.stringify(got) === JSON.stringify(exp); if (!ok) fails++; console.log((ok ? 'OK  ' : 'FAIL') + ' ' + name + ' -> ' + JSON.stringify(got) + (ok ? '' : ' (esperado ' + JSON.stringify(exp) + ')')); };
const base = { product_name: 'P', quantity: 2, costo_unitario: 100, tpv_unitario: 0, total_sin_iva: 300, descuento_porcentaje: 10, vat_percentage: 21 };
const a = calculateItemTotals(base);
eq('descuento sobre total: 300 -10% = 270', a.valor_sin_iva, 270);
eq('con IVA 21%', a.valor_con_iva, 326.7);
eq('precio neto unitario', a.pvp_neto_sin_iva, 135);
eq('beneficio línea = 270 - 2*100', a.beneficio_bruto, 70);
const b = calculateItemTotals({ ...base, total_sin_iva: 0, tpv_unitario: 480, descuento_porcentaje: 5, costo_unitario: 320 });
eq('PVP unitario 480 -5% x2 (dato antiguo)', b.valor_sin_iva, 912);
eq('sin descuento', calculateItemTotals({ ...base, descuento_porcentaje: 0 }).valor_sin_iva, 300);
eq('decimales 12.75 x3 IVA 21', calculateItemTotals({ ...base, quantity: 3, total_sin_iva: 38.25, descuento_porcentaje: 0 }).valor_con_iva, 46.28);
eq('envío 45 x1 IVA 21', calculateShippingTotals({ description: 'T', quantity: 1, costo_unitario: 45, total_sin_iva: 0, vat_percentage: 21 }).valor_con_iva, 54.45);
eq('ref primera', generateReferenceNumber('ACM', 2026, []), 'ACM-2026-001');
eq('ref tras borrar 001 (quedan 002,003)', generateReferenceNumber('ACM', 2026, ['ACM-2026-002', 'ACM-2026-003']), 'ACM-2026-004');
eq('ref ignora otras series', generateReferenceNumber('ACM', 2026, ['ACM-2025-009', 'TPG-2026-005', 'ACM-2026-001']), 'ACM-2026-002');
eq('formato moneda', formatCurrency(1234.5).replace(/\s/g, ' '), '1234,50 €');
process.exit(fails ? 1 : 0);
